const I18nCtx = createContext<{ lang: Lang; t: (key: string, vars?: Record<string, string | number>) => string; toggle: () => void; fmtTime: (sec: number) => string }>(null!);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(() => {
    try {
      return window.localStorage.getItem(LANG_STORAGE_KEY) === "en" ? "en" : "zh";
    } catch {
      return "zh";
    }
  });

  useEffect(() => {
    document.documentElement.lang = lang;
    try { window.localStorage.setItem(LANG_STORAGE_KEY, lang); } catch { /* ignore storage failures */ }
  }, [lang]);

  const t = useCallback((key: string, vars?: Record<string, string | number>): string => {
    let s = dict[lang][key] ?? dict["en"][key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    return s;
  }, [lang]);

  const toggle = useCallback(() => { setLang(l => l === "zh" ? "en" : "zh"); }, []);

  function fmtTime(sec: number): string {
    if (sec < 60) return `${sec}${t("time.sec")}`;
    if (sec < 3600) return `${Math.floor(sec / 60)}${t("time.min")} ${sec % 60}${t("time.sec")}`;
    return `${Math.floor(sec / 3600)}${t("time.hr")} ${Math.floor((sec % 3600) / 60)}${t("time.min")}`;
  }

  return createElement(I18nCtx.Provider, { value: { lang, t, toggle, fmtTime } }, children);
}

export function useT() {
  return useContext(I18nCtx);
}
